/**
 * Returned by {@link fetchBenchResults} — carries validated results plus
 * metadata about whether the data came from the live backend or the
 * deterministic fallback demo placeholder.
 */
export interface BenchResultsEnvelope {
  readonly data: BenchmarkResults;
  readonly demo: boolean;
  readonly source: string;
}

/**
 * Resolves the backend base URL. Priority:
 *   1. NEXT_PUBLIC_API_URL       (task convention)
 *   2. NEXT_PUBLIC_API_BASE_URL  (existing project .env.local key)
 *   3. http://localhost:8000     (sensible local default)
 */
export function getBenchBackendBase(): string {
  if (typeof globalThis.process !== "undefined") {
    const env = globalThis.process.env as Record<string, string | undefined>;
    const explicit = env.NEXT_PUBLIC_API_URL ?? env.NEXT_PUBLIC_API_BASE_URL;
    if (explicit) return explicit.replace(/\/$/, "");
  }
  return "http://localhost:8000";
}

/**
 * True when the resolved backend looks like a local dev origin
 * (localhost / 127.0.0.1 on any port).  Only in this case do we
 * attach the DEV_LOCAL_CAPABILITY_TOKEN preview header.
 */
function isLocalDevBase(base: string): boolean {
  try {
    const host = new URL(base).hostname.toLowerCase();
    return host === "localhost" || host === "127.0.0.1" || host === "::1";
  } catch {
    return /\blocalhost\b|127\.0\.0\.1/.test(base.toLowerCase());
  }
}

/**
 * Fetches `/api/bench/results` from the backend.
 *
 * Graceful behaviour:
 *   - If the network call throws, times out, or returns non-2xx → demo fallback.
 *   - If the response body does not match {@link BenchmarkResultsSchema} → demo fallback.
 *   - If the backend wraps the result in `{ ok, data, demo, meta }`, the inner
 *     `data` is extracted and validated.  Otherwise the raw JSON body is used.
 *
 * @returns Envelope with validated data plus `demo` flag and human-readable
 *          `source` string suitable for UI banners.
 */
export async function fetchBenchResults(): Promise<BenchResultsEnvelope> {
  const base = getBenchBackendBase();
  const endpoint = `${base}/api/bench/results`;
  try {
    const headers: Record<string, string> = { Accept: "application/json" };
    if (isLocalDevBase(base)) {
      headers["X-Noesis-Capability-Token"] = DEV_LOCAL_CAPABILITY_TOKEN;
    }
    const res = await fetch(endpoint, { headers });
    if (!res.ok) {
      throw new Error(`HTTP ${res.status}`);
    }
    const json: unknown = await res.json().catch(() => undefined);
    if (json === undefined) {
      throw new Error("Invalid JSON response");
    }

    const raw: unknown =
      json && typeof json === "object" && "data" in json
        ? (json as { data?: unknown }).data
        : json;
    const parsed = BenchmarkResultsSchema.parse(raw);

    const backendDemoFlag = Boolean(
      (json && typeof json === "object" && "demo" in json
        ? (json as { demo?: unknown }).demo
        : undefined) ??
        (json &&
          typeof json === "object" &&
          "meta" in json &&
          (json as { meta?: { demo?: unknown } }).meta &&
          typeof (json as { meta: { demo?: unknown } }).meta === "object"
          ? (json as { meta: { demo?: unknown } }).meta.demo
          : undefined) ??
        false,
    );

    return {
      data: parsed,
      demo: backendDemoFlag,
      source: backendDemoFlag
        ? `backend demo flag · ${endpoint}`
        : `backend /api/bench/results · ${base}`,
    };
  } catch (exc) {
    return {
      data: DEMO_BENCH_RESULTS,
      demo: true,
      source: `demo (fallback: ${exc instanceof Error ? exc.message : String(exc)})`,
    };
  }
}

export type LlmBenchmarkTristate = "signoff" | "reject" | "replan";

export const LlmBenchmarkResultSchema = z.object({
  task_id: z.string().min(1),
  mode: z.enum(["seeded", "adaptive"]),
  model: z.string().min(1),
  tristate: z.enum(["signoff", "reject", "replan"]).default("replan"),
  duration_ms: z.number().int().nonnegative().default(0),
  kriyakari_conf: z.number().min(0).max(1).default(0.5),
  plan_sha: z.string().min(1).default("sha-placeholder"),
  signoff_reason: z.string().default(""),
  provider: z.string().optional(),
  reachable: z.boolean().optional(),
  used_mock: z.boolean().optional(),
  error: z.string().nullable().optional(),
});
export type LlmBenchmarkResult = z.infer<typeof LlmBenchmarkResultSchema>;

export interface LlmBenchmarkEnvelope {
  readonly data: LlmBenchmarkResult;
  readonly demo: boolean;
  readonly source: string;
}

export interface RunLlmBenchmarkParams {
  readonly task_id: string;
  readonly mode: "seeded" | "adaptive";
  readonly model: "qwen2.5-coder:7b" | "deepseek-coder-v2:16b";
}

function buildMockLlmBenchmarkResult(params: RunLlmBenchmarkParams): LlmBenchmarkResult {
  const seed = Array.from(params.task_id).reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const tristateRoll = (seed * 1103515245 + 12345) % 100;
  const tristate: LlmBenchmarkTristate =
    tristateRoll < 62 ? "signoff" : tristateRoll < 88 ? "replan" : "reject";
  const confBase = tristate === "signoff" ? 0.88 : tristate === "replan" ? 0.55 : 0.31;
  const kriyakari_conf = Math.min(0.99, Math.max(0.02, confBase + ((seed % 17) - 8) / 100));
  const duration_ms = 1800 + ((seed * 7) % 14000);
  const plan_sha =
    "sha256:" +
    Array.from({ length: 56 }, (_, i) =>
      "0123456789abcdef".charAt((seed + i * 31) % 16) || "0",
    ).join("");
  const signoff_reason =
    tristate === "signoff"
      ? "Kriyak\u0101r\u012b MAC loop closed: all assertions passed, plan_sha matches deterministic replay."
      : tristate === "replan"
        ? "Intermediate check failed: planner re-issued decomposed sub-steps (mode=" + params.mode + ")."
        : "Rejected: output did not satisfy task contract for " + params.task_id + " after 3 replan rounds.";
  return {
    task_id: params.task_id,
    mode: params.mode,
    model: params.model,
    tristate,
    duration_ms,
    kriyakari_conf,
    plan_sha,
    signoff_reason,
    provider: "ollama",
    reachable: true,
    used_mock: true,
    error: null,
  };
}

export async function runLlmBenchmark(params: RunLlmBenchmarkParams): Promise<LlmBenchmarkEnvelope> {
  const base = getBenchBackendBase();
  const q = new URLSearchParams({
    task_id: params.task_id,
    mode: params.mode,
    model: params.model,
  });
  const endpoint = `${base}/llm/benchmark?${q.toString()}`;
  try {
    const headers: Record<string, string> = { Accept: "application/json" };
    if (isLocalDevBase(base)) {
      headers["X-Noesis-Capability-Token"] = DEV_LOCAL_CAPABILITY_TOKEN;
    }
    const res = await fetch(endpoint, { headers });
    if (!res.ok) {
      throw new Error(`HTTP ${res.status}`);
    }
    const json: unknown = await res.json().catch(() => undefined);
    if (json === undefined) {
      throw new Error("Invalid JSON response");
    }

    const raw: unknown =
      json && typeof json === "object" && "data" in json
        ? (json as { data?: unknown }).data
        : json;
    const coerced: LlmBenchmarkResult = {
      ...buildMockLlmBenchmarkResult(params),
      ...(raw && typeof raw === "object" ? (raw as Partial<LlmBenchmarkResult>) : {}),
      task_id: params.task_id,
      mode: params.mode,
      model: params.model,
    };
    const parsed = LlmBenchmarkResultSchema.parse(coerced);

    const backendDemoFlag = Boolean(
      (json && typeof json === "object" && "demo" in json
        ? (json as { demo?: unknown }).demo
        : undefined) ??
        (json &&
          typeof json === "object" &&
          "meta" in json &&
          (json as { meta?: { demo?: unknown } }).meta &&
          typeof (json as { meta: { demo?: unknown } }).meta === "object"
          ? (json as { meta: { demo?: unknown } }).meta.demo
          : undefined) ??
        parsed.used_mock ??
        false,
    );

    return {
      data: parsed,
      demo: backendDemoFlag,
      source: backendDemoFlag
        ? `backend demo flag · ${endpoint}`
        : `backend /llm/benchmark · ${base}`,
    };
  } catch (exc) {
    return {
      data: buildMockLlmBenchmarkResult(params),
      demo: true,
      source: `demo (fallback: ${exc instanceof Error ? exc.message : String(exc)})`,
    };
  }
}
